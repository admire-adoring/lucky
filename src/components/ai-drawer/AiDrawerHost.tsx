import { AiStageTicker } from '../ai/AiStageTicker'
import { AiDrawer } from './AiDrawer'

/**
 * AI 抽屉的宿主机 —— **`App.tsx` 在登录后挂一次**，不在任何页面里。
 *
 * ============================================================================
 * 为什么是"一次"，而且必须在路由之外
 * ============================================================================
 * 用户的要求是「**每个页面**都可以弹出侧边栏」。做到这一句有两条路：
 *
 *  ① 挂在每个页面壳里（`WorkspaceLayout` / `WorkbenchPage` / `ProjectsListPage` …）
 *     —— 要走通得记住**三处**；漏一处的症状是"那一页点了没反应"，
 *     而它不会报错，只有人点到那一页才会发现；
 *  ② 挂在路由之外一次 —— 由构造保证每页都有。
 *
 * 选 ②。代价是这一层**不在任何页面的 `.mw-root` 子树里**，拿不到内核那套令牌 ——
 * 所以抽屉的 wrapper 自己带了 `mw-root`（见 `AiDrawer` 的注释与
 * `src/styles/ai-sidebar.css` 顶部那一段）。那个代价是**一次性的、写在代码里的**；
 * 而 ① 的代价是"每次新增一个页面壳都要记得"——那是会复发的那种。
 *
 * ⚠️ 计时（`AiStageTicker`）也放在这里，理由同上：它必须活得比任何一个页面长。
 *    谁把它挪回页面里，就会出现"在抽屉里提问、阶段永远停在第一拍"
 *    （页面没挂载 ⇒ 没有计时）。两个视图共享一份会话，就必须共享一份计时。
 */
export function AiDrawerHost() {
  return (
    <>
      <AiStageTicker />
      <AiDrawer />
    </>
  )
}
