/**
 * 找这一篇的正文。三级匹配，越靠前越可信：
 *   ① 模块 + 功能 + 类型都相同（同一格里的同一类文档）
 *   ② 模块 + 功能相同
 *   ③ 名字相同
 * 都不中就返回 undefined ⇒ 页面走"这一篇的原文还没同步进来"的空态
 * （原型的判据：两种态都要能看得到，不能只演示有正文的那一种）。
 */
export function bodyOf(doc: { name: string; module: string; func: string; kind: string }): RdBlock[] | undefined {
  const byName = RD_BODIES.find((d) => d.name === doc.name)
  if (byName) return byName.body
  const byFuncKind = RD_BODIES.find((d) => d.module === doc.module && d.func === doc.func && d.kind === doc.kind)
  if (byFuncKind) return byFuncKind.body
  const byFunc = RD_BODIES.find((d) => d.module === doc.module && d.func === doc.func)
  return byFunc?.body
}
