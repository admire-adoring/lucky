/* ============================================================================
   文档正文 · 只读副本（`项目-文档原文-index.html` 的 `POOL[scope].documents[i].body`）
   ----------------------------------------------------------------------------
   文档在本仓只存索引（正文住在来源工具里）⇒ 这里保存的是应用内的只读副本，
   只有一部分篇有（原型就是如此）。没有的那几篇走"空态"，见 `DocSourcePage`。

   数据是机器转写的原文切片（6 篇 · 9~19 块）—— 手抄会改一个错一个。
      事实源仍是原型；要改正文请改原型再重跑转写。
   块只有这几类（原型 `rdBlockHtml` 认的那些）：h1~h6 / p / ul / ol / task / hr /
      img / video / quote / code / table / note。加一类要同时改三处：
      渲染（`rd-render.tsx`）/ 块→markdown（`mdOfBlocks`）/ markdown→块（`mdOfSource`）——
      少一处就是"写得进去、读不出来"。
   行内标记存在文本里（`粗` / `` `码` `` / `~~删~~` / `==高亮==` / `*斜*` /
      `[文字](url)` / `![alt](url)` / `<span style>` / `<br>` / `<sup>` / `<sub>`），
      渲染时才解析 —— 与编辑面"直接写 markdown"是同一件事。
   ============================================================================ */

/** 一段正文里能出现的块。字段与原型逐字一致（`t` 之外的字段按类型给）。 */
export interface RdBlock {
  t: string
  /** 文本块 / 引用 / 提示：一段文字；列表 / 待办：每项一条 */
  x?: string | string[]
  /** 段落样式（对齐 / 行高）—— 走行内 style，与编辑面写的是同一个地方 */
  al?: string
  lh?: string
  /** 有序列表：编号样式与起始序号 */
  num?: string
  start?: number
  /** 图片 / 视频 */
  alt?: string
  url?: string
  /** 代码块 */
  lang?: string
  /** 代码块的名称（工具条上那个输入框） */
  title?: string
  /** 代码块的样式档：light / dark / contrast（认不出的一律回 light） */
  style?: string
  /** 表格 */
  head?: string[]
  rows?: string[][]
  /** 提示块的档位（info / warn / tip / danger / note） */
  kind?: string
}

/** 一篇带正文的文档。`scope` 是它原本所属的域，只用于转写溯源。 */
export interface RdBodyDoc {
  scope: string
  name: string
  module: string
  func: string
  kind: string
  body: RdBlock[]
}

